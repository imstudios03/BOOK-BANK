PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS books (
 id TEXT PRIMARY KEY, title TEXT NOT NULL, category TEXT NOT NULL DEFAULT 'Library',
 description TEXT NOT NULL DEFAULT '', storage_key TEXT NOT NULL UNIQUE,
 is_visible INTEGER NOT NULL DEFAULT 1, page_count INTEGER NOT NULL DEFAULT 0,
 indexed_at TEXT, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS pages (
 id INTEGER PRIMARY KEY AUTOINCREMENT, book_id TEXT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
 page_number INTEGER NOT NULL, chapter TEXT NOT NULL DEFAULT '', page_title TEXT NOT NULL DEFAULT '',
 content TEXT NOT NULL DEFAULT '', UNIQUE(book_id,page_number)
);
CREATE INDEX IF NOT EXISTS idx_pages_book_page ON pages(book_id,page_number);
CREATE INDEX IF NOT EXISTS idx_books_visible ON books(is_visible);
CREATE TABLE IF NOT EXISTS bookmarks (
 id TEXT PRIMARY KEY, user_id TEXT NOT NULL, book_id TEXT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
 page_number INTEGER NOT NULL DEFAULT 1, label TEXT NOT NULL DEFAULT '',
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(user_id,book_id,page_number)
);
CREATE TABLE IF NOT EXISTS annotations (
 id TEXT PRIMARY KEY, user_id TEXT NOT NULL, book_id TEXT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
 page_number INTEGER NOT NULL, kind TEXT NOT NULL DEFAULT 'note', selected_text TEXT NOT NULL DEFAULT '',
 body TEXT NOT NULL DEFAULT '', color TEXT NOT NULL DEFAULT 'yellow',
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);